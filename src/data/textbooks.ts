// LocalStorage Custom Uploaded Textbooks Manager
const CUSTOM_TEXTBOOKS_KEY = 'ustoz_ai_custom_textbooks_v1';

export function getCustomTextbooks(): Textbook[] {
  try {
    const raw = localStorage.getItem(CUSTOM_TEXTBOOKS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (e) {
    console.error('Failed to load custom textbooks:', e);
    return [];
  }
}

export function saveCustomTextbook(tb: Textbook): void {
  const existing = getCustomTextbooks();
  const filtered = existing.filter((item) => item.id !== tb.id);
  const updated = [tb, ...filtered];
  try {
    localStorage.setItem(CUSTOM_TEXTBOOKS_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Storage full or error saving textbook:', e);
  }
}

export function getAllTextbooks(): Textbook[] {
  const custom = getCustomTextbooks();
  return [...custom, ...OFFICIAL_TEXTBOOKS];
}
